-- Iron Vault assignment feature migration. Run once in Supabase SQL Editor.
alter table public.products
  add column if not exists archived_at timestamptz,
  add column if not exists is_draft boolean not null default false,
  add column if not exists image_urls text[] not null default '{}',
  add column if not exists created_by uuid references auth.users(id) on delete set null;

update public.products
set image_urls = array[image_url]
where coalesce(cardinality(image_urls), 0) = 0 and coalesce(image_url, '') <> '';

create table if not exists public.reviews (
  id bigint generated by default as identity primary key,
  product_id bigint not null references public.products(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  rating integer not null check (rating between 1 and 5),
  comment text not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- Keep the migration compatible with projects where a simpler reviews table
-- was created before edit/delete and voting were added.
alter table public.reviews
  add column if not exists product_id bigint references public.products(id) on delete cascade,
  add column if not exists user_id uuid references auth.users(id) on delete cascade,
  add column if not exists rating integer,
  add column if not exists comment text not null default '',
  add column if not exists updated_at timestamptz not null default now();

create table if not exists public.review_votes (
  review_id bigint not null references public.reviews(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  vote smallint not null check (vote in (-1, 1)),
  created_at timestamptz not null default now(),
  primary key (review_id, user_id)
);

alter table public.reviews enable row level security;
alter table public.review_votes enable row level security;

drop policy if exists "reviews: public read" on public.reviews;
create policy "reviews: public read" on public.reviews for select to anon, authenticated using (true);
drop policy if exists "reviews: signed in create own" on public.reviews;
create policy "reviews: signed in create own" on public.reviews for insert to authenticated with check (user_id = auth.uid());
drop policy if exists "reviews: owner update" on public.reviews;
create policy "reviews: owner update" on public.reviews for update to authenticated using (user_id = auth.uid()) with check (user_id = auth.uid());
drop policy if exists "reviews: owner delete" on public.reviews;
create policy "reviews: owner delete" on public.reviews for delete to authenticated using (user_id = auth.uid());

drop policy if exists "review votes: public read" on public.review_votes;
create policy "review votes: public read" on public.review_votes for select to anon, authenticated using (true);
drop policy if exists "review votes: owner insert" on public.review_votes;
create policy "review votes: owner insert" on public.review_votes for insert to authenticated with check (user_id = auth.uid());
drop policy if exists "review votes: owner update" on public.review_votes;
create policy "review votes: owner update" on public.review_votes for update to authenticated using (user_id = auth.uid()) with check (user_id = auth.uid());
drop policy if exists "review votes: owner delete" on public.review_votes;
create policy "review votes: owner delete" on public.review_votes for delete to authenticated using (user_id = auth.uid());

grant select, insert, update, delete on public.reviews to authenticated;
grant select on public.reviews to anon;
grant select, insert, update, delete on public.review_votes to authenticated;
grant select on public.review_votes to anon;
